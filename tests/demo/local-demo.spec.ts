import {test,expect} from '@playwright/test';
import {resolve} from 'node:path';
import {tmpdir} from 'node:os';
import sharp from 'sharp';
const url=process.env.DEMO_TEST_URL??'http://127.0.0.1:8123/';

test('standalone HTML has no external dependencies, saves photo and draft, completes next and previews exact report',async({page})=>{
 const errors:string[]=[],network:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/^https?:/.test(r.url())&&(new URL(r.url()).origin!==new URL(url).origin||r.resourceType()!=='document'))network.push(r.url());});
 const photo=resolve(tmpdir(),'alys-standalone-test-photo.jpg');
 await sharp({create:{width:640,height:480,channels:3,background:'#138c89'}}).jpeg().toFile(photo);
 await page.goto(url);
 await expect(page.getByRole('heading',{name:'Today’s Route',exact:true})).toBeVisible();
 await expect(page.getByRole('status')).toHaveText('Saved locally · no cloud sync');
 await page.getByRole('button',{name:'Start service →',exact:true}).first().click();
 await expect(page.getByRole('heading',{name:'Demo Residence 01',exact:true})).toBeVisible();
 const chemicalHistory=page.getByRole('region',{name:'Main pool chemical history'});
 await expect(chemicalHistory).toContainText('Last 30 days');
 await expect(chemicalHistory).toContainText('Liquid Chlorine');
 await expect(page.getByLabel('Main pool Free Chlorine',{exact:true})).toHaveValue('');
 await page.getByRole('button',{name:'COMPLETE & NEXT →',exact:true}).click();
 await expect(page.locator('#visit-error')).toContainText('Free Chlorine is required');
 await page.getByRole('button',{name:'Mark all done',exact:true}).click();
 await page.getByRole('button',{name:'Main pool FC 1 ppm',exact:true}).click();
 await expect(page.getByLabel('Main pool Free Chlorine',{exact:true})).toHaveValue('1');
 await page.getByRole('button',{name:'Main pool FC 3 ppm',exact:true}).click();
 await expect(page.getByLabel('Main pool Free Chlorine',{exact:true})).toHaveValue('3');
 await page.getByRole('button',{name:'Main pool FC 5 ppm',exact:true}).click();
 await expect(page.getByLabel('Main pool Free Chlorine',{exact:true})).toHaveValue('5');
 await page.getByLabel('Main pool Free Chlorine',{exact:true}).fill('3.5');
 await expect(page.getByRole('button',{name:'Main pool FC 5 ppm',exact:true})).toHaveAttribute('aria-pressed','false');
 for(const value of [7,7.2,7.4,7.6,7.8,8]){
  await page.getByRole('button',{name:`Main pool pH ${value.toFixed(1)}`,exact:true}).click();
  await expect(page.getByLabel('Main pool pH',{exact:true})).toHaveValue(String(value));
 }
 await page.getByLabel('Main pool Free Chlorine',{exact:true}).fill('3');
 await page.getByLabel('Main pool pH',{exact:true}).fill('7.5');
 await page.getByRole('combobox',{name:'Add chemical for Main pool'}).selectOption('Liquid Chlorine');
 await page.getByLabel('Liquid Chlorine amount',{exact:true}).fill('0.5');
 await page.getByRole('combobox',{name:'Add chemical for Main pool'}).selectOption('Muriatic Acid');
 await page.getByLabel('Muriatic Acid amount',{exact:true}).fill('12');
 await page.locator('#photo-input').setInputFiles(photo);
 await expect(page.getByAltText('Captured service photo 1')).toBeVisible();
 await expect(page.getByRole('status')).toHaveText('Saved locally · no cloud sync');
 await page.reload();
 await expect(page.getByLabel('Main pool Free Chlorine',{exact:true})).toHaveValue('3');
 await expect(page.getByLabel('Main pool pH',{exact:true})).toHaveValue('7.5');
 await expect(page.getByLabel('Liquid Chlorine amount',{exact:true})).toHaveValue('0.5');
 await expect(page.getByAltText('Captured service photo 1')).toBeVisible();
 await expect(page.getByRole('checkbox',{name:'Brush Pool',exact:true})).toBeChecked();
 await page.screenshot({path:'/tmp/alys-standalone-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'COMPLETE & NEXT →',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Demo Residence 02',exact:true})).toBeVisible();
 await expect(page.getByLabel('Main pool Free Chlorine',{exact:true})).toHaveValue('');
 await expect(page.getByRole('checkbox',{name:'Brush Pool',exact:true})).not.toBeChecked();
 await page.getByRole('link',{name:'History',exact:true}).click();
 const current=page.locator('.history-record').first();
 await current.locator('summary').click();
 await expect(current).toContainText('Free Chlorine: 3 ppm');
 await expect(current).toContainText('Muriatic Acid: 12 fl oz');
 await current.getByRole('button',{name:'Preview customer report',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await expect(dialog).toContainText('No email has been sent.');
 await expect(dialog.locator('.report')).toContainText('Liquid Chlorine: 0.5 gal');
 await expect(dialog.locator('.report')).not.toContainText('Fictional access note');
 await expect(dialog.getByAltText('Service photo 1')).toBeVisible();
 expect(network).toEqual([]);expect(errors).toEqual([]);
});

test('client and pool settings persist and input renders safely as text',async({page})=>{
 await page.goto(url);
 await expect(page.getByRole('heading',{name:'Today’s Route'})).toBeVisible();
 await page.getByRole('link',{name:'Clients',exact:true}).click();
 await page.getByRole('button',{name:'＋ Add demo client'}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Client name',{exact:true}).fill('Fictional <script>client</script>');
 await dialog.getByLabel('Property name',{exact:true}).fill('Fictional Test Property');
 await dialog.getByLabel('Service address',{exact:true}).fill('Fictional address, FL');
 await dialog.getByRole('button',{name:'Save client',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Fictional <script>client</script>',exact:true})).toBeVisible();
 const card=page.locator('.client-card').filter({has:page.getByRole('heading',{name:'Fictional <script>client</script>',exact:true})});
 await card.getByRole('button',{name:'Pool settings',exact:true}).click();
 await dialog.getByLabel('Pool / spa name',{exact:true}).fill('Demo Test Pool');
 await dialog.getByRole('checkbox',{name:'Require a service photo',exact:true}).check();
 await dialog.getByRole('button',{name:'Save pool',exact:true}).click();
 await expect(card).toContainText('Demo Test Pool');
 await expect(card).toContainText('Photo required');
 await page.reload();
 await expect(page.getByRole('heading',{name:'Fictional <script>client</script>',exact:true})).toBeVisible();
 await expect(page.getByText('Demo Test Pool',{exact:true})).toBeVisible();
 expect(await page.locator('main script').count()).toBe(0);
});
