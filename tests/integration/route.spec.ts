import { test,expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { createClient } from '@supabase/supabase-js';

type Fixture={url:string;email:string;password:string;userId:string;orgId:string;otherUserId:string;date:string;stops:{id:string;propertyId:string;poolId:string;customerId:string;name:string}[]};
const fixture=JSON.parse(readFileSync('/tmp/alys-integration-fixture.json','utf8')) as Fixture;
try{process.loadEnvFile('.env.local');}catch{/* CI may inject local variables. */}
if(!['localhost','127.0.0.1'].includes(new URL(fixture.url).hostname))throw new Error('Integration tests only target local Supabase.');
const admin=createClient(fixture.url,process.env.SUPABASE_SERVICE_ROLE_KEY!,{auth:{persistSession:false,autoRefreshToken:false}});

test('mobile service persists JPEG, snapshot and one outbox; offline visit survives reload and syncs once',async({page,context,baseURL})=>{
  // Local historical service fixture: real relational records from three days ago.
  const historicalDate=new Date(Date.now()-3*86400000);
  const day=new Intl.DateTimeFormat('en-CA',{timeZone:'America/New_York',year:'numeric',month:'2-digit',day:'2-digit'}).format(historicalDate);
  const historicalId=randomUUID();
  const {data:historicalStop,error:historicalStopError}=await admin.from('route_stops').insert({organization_id:fixture.orgId,property_id:fixture.stops[0].propertyId,technician_id:fixture.userId,service_date:day,status:'completed',position:1}).select('id').single();
  expect(historicalStopError).toBeNull();
  const oldPool={pool_id:fixture.stops[0].poolId,pool_name:'Pool 1',tasks:['Test Water'],readings:{fc:0,ph:7.3},dosages:[{product:'Liquid Chlorine',quantity:0.5,unit:'gal'}]};
  const {error:historicalError}=await admin.from('visits').insert({id:historicalId,organization_id:fixture.orgId,route_stop_id:historicalStop!.id,technician_id:fixture.userId,completed_at:historicalDate.toISOString(),snapshot:{property_name:'Test Property 1',customer_name:'Fictional Client 1',notes:'',pools:[oldPool]}});
  expect(historicalError).toBeNull();
  const {error:readingError}=await admin.from('chemical_readings').insert({organization_id:fixture.orgId,visit_id:historicalId,pool_id:fixture.stops[0].poolId,fc:0,ph:7.3});expect(readingError).toBeNull();
  const {error:doseError}=await admin.from('chemical_dosages').insert({organization_id:fixture.orgId,visit_id:historicalId,pool_id:fixture.stops[0].poolId,product:'Liquid Chlorine',quantity:0.5,unit:'gal'});expect(doseError).toBeNull();
  const browserErrors:string[]=[];
  page.on('pageerror',error=>browserErrors.push(error.message));
  page.on('response',async response=>{if(/\/api\/(photos|visits)(?:\?|$)/.test(response.url())&&response.status()>=400)console.log('API failure',new URL(response.url()).pathname,response.status(),await response.json());});
  await page.goto('/login');
  await page.getByLabel('Email',{exact:true}).fill(fixture.email);
  await page.getByLabel('Password',{exact:true}).fill(fixture.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Today’s Route'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Test Property 1',exact:true})).toBeVisible();
  await page.screenshot({path:'/tmp/alys-route-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Start service →'}).first().click();
  await expect(page.getByRole('heading',{name:'Test Property 1',exact:true})).toBeVisible();
  await expect(page.getByLabel('Pool 1 Free Chlorine (ppm)',{exact:true})).toHaveValue('');
  await expect(page.getByLabel('Pool 1 pH',{exact:true})).toHaveValue('');
  const chemistry=page.getByRole('region',{name:'Pool 1 chemical history'});
  await expect(chemistry.getByRole('heading',{name:'Chemical history',exact:true})).toBeVisible();
  await expect(chemistry).toContainText('Last 30 days');
  await expect(chemistry).toContainText('0 ppm');
  await expect(chemistry).toContainText('Liquid Chlorine: 0.5 gal');
  await page.screenshot({path:'/tmp/alys-mobile-service.png',fullPage:true});
  await page.getByLabel('Skim Surface',{exact:true}).check();
  await page.getByLabel('Test Water',{exact:true}).check();
  await page.getByLabel('Pool 1 Free Chlorine (ppm)',{exact:true}).fill('3');
  await page.getByLabel('Pool 1 pH',{exact:true}).fill('7.5');
  await page.getByLabel('Add chemical for Pool 1',{exact:true}).selectOption('Liquid Chlorine');
  await page.getByLabel('Liquid Chlorine amount',{exact:true}).fill('1');
  await page.getByLabel('Add chemical for Pool 1',{exact:true}).selectOption('Muriatic Acid');
  await page.getByLabel('Muriatic Acid amount',{exact:true}).fill('12');
  await page.locator('input[type=file]').setInputFiles('/tmp/alys-test-photo.jpg');
  await expect(page.getByAltText('Captured service photo')).toHaveCount(1);
  await page.screenshot({path:'/tmp/alys-service-mobile.png',fullPage:true});
  const submitted=page.waitForRequest(request=>request.url().endsWith('/api/visits')&&request.method()==='POST');
  await page.getByRole('button',{name:'COMPLETE & NEXT →',exact:true}).click();
  const payload=(await submitted).postDataJSON();
  await expect(page.getByRole('heading',{name:'Test Property 2',exact:true})).toBeVisible();
  await expect.poll(async()=>{const {data,error}=await admin.from('visits').select('id').eq('route_stop_id',fixture.stops[0].id);if(error)throw error;return data.length;}).toBe(1);
  const {data:first,error:firstError}=await admin.from('visits').select('id,snapshot').eq('route_stop_id',fixture.stops[0].id).single();
  expect(firstError).toBeNull();
  expect(first!.snapshot.pools[0].tasks).toEqual(['Skim Surface','Test Water']);
  expect(first!.snapshot.pools[0].readings).toMatchObject({fc:3,ph:7.5});
  expect(first!.snapshot.pools[0].dosages).toEqual([{product:'Liquid Chlorine',quantity:1,unit:'gal'},{product:'Muriatic Acid',quantity:12,unit:'fl oz'}]);
  expect(JSON.stringify(first!.snapshot)).not.toContain('PRIVATE GATE');
  const {data:photos}=await admin.from('visit_photos').select('storage_path').eq('visit_id',first!.id);
  expect(photos).toHaveLength(1);
  const signed=await page.request.get('/api/photos?path='+encodeURIComponent(photos![0].storage_path));
  expect(signed.status()).toBe(200);
  const signedBody=await signed.json();expect((await page.request.get(signedBody.url)).status()).toBe(200);
  const repeat=await page.request.post('/api/visits',{data:payload,headers:{Origin:baseURL!,'X-ALYS-User-ID':fixture.userId,'X-ALYS-Organization-ID':fixture.orgId}});
  expect(repeat.status()).toBe(200);expect((await repeat.json()).visit_id).toBe(first!.id);
  const {data:logs}=await admin.from('email_delivery_logs').select('id,status,attempts').eq('visit_id',first!.id);
  expect(logs).toHaveLength(1);expect(logs![0].status).toBe('pending');expect(logs![0].attempts).toBe(0);
  // The same browser uses actual IndexedDB blobs and a real offline network boundary.
  await page.getByLabel('Pool 2 Free Chlorine (ppm)',{exact:true}).fill('2.5');
  await page.getByLabel('Pool 2 pH',{exact:true}).fill('7.4');
  await page.getByRole('button',{name:'Mark all done',exact:true}).click();
  await page.locator('input[type=file]').setInputFiles('/tmp/alys-test-photo.jpg');
  await expect(page.getByAltText('Captured service photo')).toHaveCount(1);
  await page.waitForFunction(()=>navigator.serviceWorker.controller!==null);
  await context.setOffline(true);
  await page.getByRole('button',{name:'COMPLETE & NEXT →',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Test Property 3',exact:true})).toBeVisible();
  await expect(page.getByText('1 visit waiting to sync',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText('1 visit waiting to sync',{exact:true})).toBeVisible({timeout:30000});
  const {count:before}=await admin.from('visits').select('id',{count:'exact',head:true}).eq('route_stop_id',fixture.stops[1].id);expect(before).toBe(0);
  await context.setOffline(false);
  await expect.poll(async()=>{const {count,error}=await admin.from('visits').select('id',{count:'exact',head:true}).eq('route_stop_id',fixture.stops[1].id);if(error)throw error;return count;},{timeout:30000}).toBe(1);
  await page.goto('/history');
  await expect(page.getByRole('heading',{name:'Visit History',exact:true})).toBeVisible();
  await expect(page.getByText('Test Property 1',{exact:true}).first()).toBeVisible();
  await expect(page.getByText('Test Property 2',{exact:true})).toBeVisible();
  expect(browserErrors).toEqual([]);
});

test('anonymous API access and cross-origin mutations are rejected',async({request})=>{
  expect((await request.get('/api/route')).status()).toBe(401);
  const response=await request.post('/api/visits',{data:{},headers:{Origin:'https://untrusted.example'}});
  expect([401,403]).toContain(response.status());
});

